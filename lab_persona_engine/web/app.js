  function initRecog() {
    if (!SpeechRec) return null;
    const r = new SpeechRec();
    r.lang = lang === 'en' ? 'en-US' : 'zh-CN';
    r.interimResults = true;
    r.continuous = false;
    r.maxAlternatives = 1;
    r.onstart = () => {
      listening = true;
      micBtn.classList.add('listening');
      micBtn.setAttribute('aria-pressed', 'true');
      input.placeholder = T('listening');
      if (synth) synth.cancel();
    };
    r.onresult = (e) => {
      let interim = '';
      let fin = '';
      for (let i = e.resultIndex; i < e.results.length; i++) {
        const t = e.results[i][0].transcript;
        if (e.results[i].isFinal) fin += t; else interim += t;
      }
      const text = (fin || interim).trim();
      if (text) {
        input.value = text;
        voiceFinal = !!fin;
        input.style.height = 'auto';
        input.style.height = Math.min(input.scrollHeight, 110) + 'px';
      }
    };
    r.onerror = (e) => {
      const map = {
        'not-allowed': T('recogNotAllowed'),
        'audio-capture': T('recogNoMic'),
        'no-speech': T('recogNoSpeech'),
        network: T('recogNetwork'),
      };
      if (e.error !== 'aborted') showToast(map[e.error] || (T('recogFailed') + e.error));
    };
    r.onend = () => {
      listening = false;
      micBtn.classList.remove('listening');
      micBtn.setAttribute('aria-pressed', 'false');
      input.placeholder = T('placeholder');
      if (voiceFinal) {
        voiceFinal = false;
        const text = input.value.trim();
        if (text) {
          if (state.busy) showToast(T('busyVoice'));
          else send(text);
        }
      }
    };
    return r;
  }

  function toggleVoice() {
    if (!recog) recog = initRecog();
    if (!recog) {
      showToast(T('unsupportedVoice'));
      return;
    }
    if (listening) {
      try { recog.stop(); } catch (e) { /* ignore */ }
      return;
    }
    voiceFinal = false;
    try {
      recog.start();
    } catch (e) {
      try { recog.stop(); } catch (_) { /* ignore */ }
      setTimeout(() => { try { recog.start(); } catch (_) { /* ignore */ } }, 250);
    }
  }

