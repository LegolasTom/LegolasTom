  function scoreEnVoice(v) {
    const n = (v.name || '').toLowerCase();
    let s = 0;
    if (/(^|[^a-z])female([^a-z]|$)|woman/.test(n)) s += 100;
    EN_FEMALE_HINTS.forEach((hint, i) => { if (n.includes(hint)) s += 60 - i; });
    if (/(^|[^a-z])male([^a-z]|$)/.test(n)) s -= 300;
    EN_MALE_HINTS.forEach((hint) => { if (n.includes(hint)) s -= 150; });
    if (/^en[-_]us/i.test(v.lang)) s += 12;
    else if (/^en[-_]gb/i.test(v.lang)) s += 8;
    else if (/^en/i.test(v.lang)) s += 3;
    if (v.localService) s += 1;
    return s;
  }

  function pickVoice() {
    if (!synth) return;
    const voices = synth.getVoices() || [];
    zhVoice = voices.find((v) => /zh[-_]CN/i.test(v.lang) && /female|huihui|xiaoxiao|yaoyao|tingting/i.test(v.name)) ||
      voices.find((v) => /zh[-_]CN/i.test(v.lang)) ||
      voices.find((v) => /^zh/i.test(v.lang)) || null;
    const en = voices.filter((v) => /^en/i.test(v.lang));
    en.sort((a, b) => scoreEnVoice(b) - scoreEnVoice(a));
    enVoice = en[0] || null;
    enVoiceFemale = !!enVoice && scoreEnVoice(enVoice) > 0;
  }
  if (synth) {
    pickVoice();
    synth.onvoiceschanged = pickVoice;
  }

  function speak(text) {
    if (!state.voiceOn || !synth) return;
    const clean = text.replace(/[*#`]/g, '').replace(/[~～]/g, lang === 'en' ? ',' : '，').trim();
    if (!clean) return;
    if (!zhVoice || !enVoice) pickVoice();
    try {
      synth.cancel();
      const u = new SpeechSynthesisUtterance(clean);
      u.lang = lang === 'en' ? 'en-US' : 'zh-CN';
      const voice = lang === 'en' ? enVoice : zhVoice;
      if (voice) {
        u.voice = voice;
        if (voice.lang) u.lang = voice.lang;  // 跟随所选音色，避免语言不匹配被浏览器换回默认男声
      }
      u.rate = lang === 'en' ? 1.0 : 1.05;
      // 系统只有男声时提高音高，保证听感上仍是女声
      u.pitch = lang === 'en' ? (enVoiceFemale ? 1.08 : 1.3) : 1.12;
      u.onstart = () => { state.speaking = true; setStatus('speaking', T('statusSpeaking')); };
      u.onend = () => { state.speaking = false; setStatus('', T('statusOnline')); };
      u.onerror = () => { state.speaking = false; setStatus('', T('statusOnline')); };
      synth.speak(u);
    } catch (e) { /* ignore */ }
  }

